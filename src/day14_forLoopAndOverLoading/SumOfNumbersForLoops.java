package day14_forLoopAndOverLoading;

public class SumOfNumbersForLoops {

    public static void main(String[] args) {

        int number = 100;
        int sum = 0;


        for (int i = 1; i <= number; i++) {
            sum += i; // sum = sum + i .

        }
        System.out.println (sum);

    }
}
