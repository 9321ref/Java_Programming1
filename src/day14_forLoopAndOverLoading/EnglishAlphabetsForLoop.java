package day14_forLoopAndOverLoading;

public class EnglishAlphabetsForLoop {

    public static void main(String[] args) {

        for ( char i = 'A'; i <= 'Z'; i++) {

            System.out.println(i + " ");  /* A
                                             B
                                             C
                                             D
                                             E
                                         */

        }
    }
}
